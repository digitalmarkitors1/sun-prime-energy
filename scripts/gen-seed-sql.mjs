// Generate supabase/migrations/0002_seed.sql from the committed data/*.ts.
// Running this SQL in the Supabase SQL editor seeds all content WITHOUT needing
// the service_role/secret key (the SQL editor runs as a superuser, past RLS).
//
//   npm run gen:seed

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { site } from "../data/site.ts";
import { landingPages } from "../data/landingPages.ts";
import { seoDefaults } from "../data/seoDefaults.ts";
import { blogPosts } from "../data/blog.ts";

const here = dirname(fileURLToPath(import.meta.url));
const outFile = join(here, "..", "supabase", "migrations", "0002_seed.sql");

// --- SQL literal helpers (dollar-quoted → no escaping headaches) ------------
const TAG = "$sunp$";
const txt = (v) => (v == null ? "NULL" : `${TAG}${String(v)}${TAG}`);
const jsonb = (v) => `${TAG}${JSON.stringify(v ?? null)}${TAG}::jsonb`;
const bool = (v) => (v ? "true" : "false");
const int = (v) => String(v | 0);

const SHORT_NAME = site.shortName;
const fullTitle = (d) => (d.absoluteTitle ? d.title : `${d.title} — ${SHORT_NAME}`);

const lines = [];
lines.push("-- AUTO-GENERATED by scripts/gen-seed-sql.mjs — seed content for the Sunprime CMS.");
lines.push("-- Run AFTER 0001_sunprime_cms.sql, in the Supabase SQL editor.");
lines.push("-- Safe to re-run: every statement upserts on the primary key.\n");

// 1. site content
lines.push("-- Global site content");
lines.push(
  `insert into public.sunprime_content_singletons (key, data) values ('site', ${jsonb(site)})\n` +
    `  on conflict (key) do update set data = excluded.data;\n`,
);

// 2. landing pages
lines.push("-- SEO landing pages");
Object.values(landingPages).forEach((p, i) => {
  lines.push(
    "insert into public.sunprime_landing_pages " +
      "(slug, nav_label, eyebrow, meta_title, meta_description, h1_lead, h1_highlight, lead, intro, benefits_heading, benefits, sector, faq_heading, faqs, related, published, sort_order) values (" +
      [
        txt(p.slug),
        txt(p.navLabel),
        txt(p.eyebrow),
        txt(p.metaTitle),
        txt(p.metaDescription),
        txt(p.h1Lead),
        txt(p.h1Highlight),
        txt(p.lead),
        jsonb(p.intro),
        txt(p.benefitsHeading),
        jsonb(p.benefits),
        txt(p.sector ?? null),
        txt(p.faqHeading ?? null),
        jsonb(p.faqs),
        jsonb(p.related),
        bool(true),
        int(i),
      ].join(", ") +
      ")\n  on conflict (slug) do update set " +
      "nav_label=excluded.nav_label, eyebrow=excluded.eyebrow, meta_title=excluded.meta_title, meta_description=excluded.meta_description, h1_lead=excluded.h1_lead, h1_highlight=excluded.h1_highlight, lead=excluded.lead, intro=excluded.intro, benefits_heading=excluded.benefits_heading, benefits=excluded.benefits, sector=excluded.sector, faq_heading=excluded.faq_heading, faqs=excluded.faqs, related=excluded.related, published=excluded.published, sort_order=excluded.sort_order;",
  );
});
lines.push("");

// 3. SEO meta for standard routes
lines.push("-- Per-route SEO meta");
Object.values(seoDefaults).forEach((d) => {
  lines.push(
    "insert into public.sunprime_seo_meta (path, title, description, canonical, og_image, noindex) values (" +
      [
        txt(d.path),
        txt(fullTitle(d)),
        txt(d.description),
        txt(`${site.url}${d.path === "/" ? "" : d.path}`),
        txt(site.heroImage),
        bool(false),
      ].join(", ") +
      ")\n  on conflict (path) do update set title=excluded.title, description=excluded.description, canonical=excluded.canonical, og_image=excluded.og_image, noindex=excluded.noindex;",
  );
});
lines.push("");

// 4. blog posts
lines.push("-- Blog posts");
blogPosts.forEach((p) => {
  lines.push(
    "insert into public.sunprime_blog_posts " +
      "(slug, title, excerpt, body, category, read_time, author, cover_image, meta_title, meta_description, og_image, published, featured, published_at, sort_order) values (" +
      [
        txt(p.slug),
        txt(p.title),
        txt(p.excerpt),
        txt(p.body),
        txt(p.category),
        txt(p.readTime),
        txt(p.author),
        txt(p.coverImage),
        txt(p.metaTitle ?? null),
        txt(p.metaDescription ?? null),
        txt(p.ogImage ?? null),
        bool(p.published),
        bool(p.featured),
        txt(p.publishedAt),
        int(p.sortOrder),
      ].join(", ") +
      ")\n  on conflict (slug) do update set title=excluded.title, excerpt=excluded.excerpt, body=excluded.body, category=excluded.category, read_time=excluded.read_time, author=excluded.author, cover_image=excluded.cover_image, meta_title=excluded.meta_title, meta_description=excluded.meta_description, og_image=excluded.og_image, published=excluded.published, featured=excluded.featured, published_at=excluded.published_at, sort_order=excluded.sort_order;",
  );
});
lines.push("");

writeFileSync(outFile, lines.join("\n"));
console.log(`✓ Wrote ${outFile}`);
console.log(
  `  ${Object.keys(landingPages).length} landing pages, ${Object.keys(seoDefaults).length} SEO rows, ${blogPosts.length} blog posts.`,
);
